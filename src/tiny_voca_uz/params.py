"""Parameter accounting: per-module counts, tensor shapes and a width sweep.

    python -m tiny_voca_uz.params               # student report (JSON)
    python -m tiny_voca_uz.params --markdown    # full audit table (docs/parameter_audit.md)
"""

import argparse
from dataclasses import replace
import json
from pathlib import Path

from .config import Config, english_teacher_config, teacher_config
from .model import TinyVocaUZ


def groups(model):
    return {
        "embeddings (token, stress, voice, frame position)": [model.tokens, model.stress, model.voices, model.frame_voices,
                                                              model.frame_position],
        "text encoder": [model.encoder],
        "duration predictor": [model.duration],
        "prosody stack A + pitch/voicing/energy head": [model.prosody_stack, model.prosody_head, model.prosody_projection],
        "acoustic stack B": [model.acoustic_stack],
        "source-filter head": [model.vocoder],
    }


def count(modules):
    return sum(p.numel() for module in modules for p in module.parameters())


def parameter_report(config):
    model = TinyVocaUZ(config)
    parts = {name: count(modules) for name, modules in groups(model).items()}
    total = sum(p.numel() for p in model.parameters())
    if sum(parts.values()) != total:
        raise RuntimeError("parameter groups do not cover the model")
    return {"parts": parts, "total": total, "fp32_MB": round(total * 4 / 1e6, 3), "fp16_MB": round(total * 2 / 1e6, 3),
            "int8_MB": round(total / 1e6, 3)}


def shapes(config):
    return [(name, tuple(p.shape), p.numel()) for name, p in TinyVocaUZ(config).named_parameters()]


def sweep(base=Config()):
    rows = []
    for channels, feedforward in ((80, 256), (80, 320), (96, 320), (96, 384), (112, 384), (128, 384)):
        for layers in ((3, 1, 2), (3, 2, 3), (4, 2, 3)):
            c = replace(base, channels=channels, feedforward=feedforward, predictor_channels=min(channels, 96),
                        encoder_layers=layers[0], prosody_layers=layers[1], acoustic_layers=layers[2])
            rows.append((channels, feedforward, layers, parameter_report(c)["total"]))
    return rows


def markdown():
    lines = ["# Parameter audit", "", "Generated by `python -m tiny_voca_uz.params --markdown`.", ""]
    configs = {"Original Tiny-Voca (English, 76 symbols, 2 voices)": english_teacher_config(),
               "Teacher architecture with the Uzbek inventory (1 voice)": teacher_config(),
               "Tiny-Voca-UZ-1M student (default)": Config()}
    reports = {name: parameter_report(c) for name, c in configs.items()}
    names = list(reports)
    lines += ["## Per-module counts", "", "| Module | " + " | ".join(names) + " |", "|---|" + "---:|" * len(names)]
    for part in reports[names[0]]["parts"]:
        lines.append(f"| {part} | " + " | ".join(f"{reports[n]['parts'][part]:,}" for n in names) + " |")
    lines.append("| **total** | " + " | ".join(f"**{reports[n]['total']:,}**" for n in names) + " |")
    lines.append("| fp32 / fp16 / int8 MB | " + " | ".join(
        f"{reports[n]['fp32_MB']} / {reports[n]['fp16_MB']} / {reports[n]['int8_MB']}" for n in names) + " |")
    lines += ["", "## Width / depth sweep (student variants)", "",
              "| channels | feedforward | layers (enc, prosody, acoustic) | parameters |", "|---:|---:|---|---:|"]
    for channels, feedforward, layers, total in sweep():
        lines.append(f"| {channels} | {feedforward} | {layers} | {total:,} |")
    for title, c in (("Student", Config()), ("Teacher (Uzbek inventory)", teacher_config())):
        lines += ["", f"## {title} tensor shapes", "", "| Parameter | Shape | Count |", "|---|---|---:|"]
        lines += [f"| `{name}` | {list(shape)} | {n:,} |" for name, shape, n in shapes(c)]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Count parameters without any weights")
    parser.add_argument("--markdown", action="store_true", help="print the full audit as Markdown")
    parser.add_argument("--teacher", action="store_true", help="report the teacher architecture instead")
    parser.add_argument("--config", type=Path, help="JSON file overriding student defaults (e.g. configs/model_1m.json)")
    args = parser.parse_args()
    if args.markdown:
        print(markdown(), end="")
    else:
        config = teacher_config() if args.teacher else Config()
        if args.config:
            config = Config.from_dict({**config.to_dict(), **json.loads(args.config.read_text())})
        print(json.dumps(parameter_report(config), indent=2))


if __name__ == "__main__":
    main()
